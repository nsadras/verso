import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

async function openTopics(page: Page, mobile: boolean) {
  if (mobile) await page.getByRole('button', { name: 'Open topics', exact: true }).click()
}

async function topic(page: Page, name: string, mobile: boolean) {
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeEnabled()
  await openTopics(page, mobile)
  await page.getByRole('button', { name: '+ New chat', exact: true }).click()
  await openTopics(page, mobile)
  await page.getByRole('button', { name: 'Rename topic', exact: true }).click()
  await page.getByRole('textbox', { name: 'Topic name', exact: true }).fill(name)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name, exact: true })).toHaveAttribute('aria-current', 'page')
  if (mobile) await page.getByRole('button', { name: 'Close topics', exact: true }).click()
}

async function panel(page: Page, name: 'Notebook' | 'Conversation', mobile: boolean) {
  if (mobile) await page.getByRole('navigation', { name: 'Workspace panel' }).getByRole('button', { name: name === 'Conversation' ? 'Chat' : name, exact: true }).click()
}

