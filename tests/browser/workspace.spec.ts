test('LaTeX renders in streamed replies and notebook previews while preserving source', async ({ page, isMobile }) => {
  const source = readFileSync(new URL('../fixtures/math.md', import.meta.url), 'utf8')
  const errors: string[] = []
  const externalFonts: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (request.resourceType() === 'font' && new URL(request.url()).origin !== new URL(page.url()).origin) {
      externalFonts.push(request.url())
    }
  })
  await topic(page, `Math ${Date.now()}`, isMobile)
  const editor = page.getByRole('textbox', { name: 'Message', exact: true })
  await editor.fill('math-response')
  await editor.press('Enter')
  const reply = page.locator('.diary-response')
  await expect(reply.locator('.katex').first()).toBeVisible()
  await expect(editor).toBeDisabled()
  await expect(editor).toBeEnabled()
  expect(await reply.locator('math annotation').allTextContents()).toEqual(expect.arrayContaining([
    String.raw`\mathbf{v}`, 'V^*', 'v^i', String.raw`\omega_i`,
  ]))
  expect(await reply.locator('math[display="block"] annotation').allTextContents()).toEqual(expect.arrayContaining([
    String.raw`\omega(\mathbf{v}) = \text{scalar}`,
    String.raw`\frac{x^2}{1 + \sqrt{y}} = \sum_{i=1}^{n} a_i`,
  ]))
  await expect(reply.locator('.katex-error')).toHaveCount(1)
  await expect(reply).toContainText('The page still works after an unfinished formula.')
  await expect(reply).toContainText('The notebook costs $5; refills cost $2.')
  await expect(reply.locator('p > code')).toHaveText(String.raw`$\mathbf{v}$`)
  await expect(reply.locator('pre code')).toContainText(String.raw`$$\omega(\mathbf{v}) = \text{scalar}$$`)
  const wide = reply.locator('.katex-display').last()
  expect(await wide.evaluate(element => element.scrollWidth > element.clientWidth)).toBeTruthy()
  await wide.evaluate(element => { element.scrollLeft = element.scrollWidth })
  expect(await wide.evaluate(element => element.scrollLeft)).toBeGreaterThan(0)
  const surface = page.locator('.diary-surface')
  expect(await surface.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy()
  await surface.evaluate(element => { element.scrollTop = 0 })
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: `test-results/diary-math-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true })

  await panel(page, 'Notebook', isMobile)
  const notebook = page.getByRole('textbox', { name: 'Notebook', exact: true })
  await notebook.fill(source)
  await expect(page.getByText('✓ Saved on host')).toBeVisible()
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  const preview = page.locator('.notebook-preview')
  expect(await preview.locator('math annotation').allTextContents()).toEqual(await reply.locator('math annotation').allTextContents())
  expect(await preview.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export .md' }).click()
  expect(readFileSync((await (await download).path())!, 'utf8')).toBe(source)
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(notebook).toHaveValue(source)
  await page.reload()
  await panel(page, 'Notebook', isMobile)
  await expect(notebook).toHaveValue(source)
  expect(errors).toEqual([])
  expect(externalFonts).toEqual([])
})

